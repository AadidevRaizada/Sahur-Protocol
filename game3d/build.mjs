// Bundles the 3D Bubble-fight renderer (three + React + react-three-fiber + postprocessing + the promo's
// models) with esbuild and inlines it into Sahur_Protocol.html between the R3D markers, so the game stays
// one static HTML file.
//
//   node game3d/build.mjs          build + inline
//   node game3d/build.mjs --check  build only, print sizes
//
// Dependencies come from the promo project (marketing/video/sahur-promo/node_modules); run `npm install`
// there first if that folder is missing.
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const promo = path.join(root, 'marketing/video/sahur-promo');
const require = createRequire(path.join(promo, 'package.json'));
const esbuild = require('esbuild');

const HTML = path.join(root, 'Sahur_Protocol.html');
const BEGIN = '<!-- R3D:BEGIN (generated by game3d/build.mjs from game3d/src - do not edit by hand) -->';
const END = '<!-- R3D:END -->';
const check = process.argv.includes('--check');

const FONTS = {
  PressStart2P: ['Press Start 2P', ['400']],
  PixelifySans: ['Pixelify Sans', ['400', '600', '700']],
  Inter: ['Inter', ['500', '600', '700', '800']],
  Montserrat: ['Montserrat', ['500']],
};

/** remotion -> small stand-ins (src/shims). Remotion itself is never bundled. */
const shims = {
  name: 'remotion-shims',
  setup(b) {
    b.onResolve({ filter: /^remotion$/ }, () => ({ path: path.join(here, 'src/shims/remotion.ts') }));
    b.onResolve({ filter: /^@remotion\/google-fonts\// }, (a) => ({ path: a.path.split('/').pop(), namespace: 'gfont' }));
    b.onLoad({ filter: /.*/, namespace: 'gfont' }, (a) => {
      const f = FONTS[a.path];
      if (!f) throw new Error('no font shim for ' + a.path);
      return {
        contents: `import { makeLoader } from ${JSON.stringify(path.join(here, 'src/shims/googleFont.ts').replace(/\\/g, '/'))};
export const loadFont = makeLoader(${JSON.stringify(f[0])}, ${JSON.stringify(f[1])});`,
        loader: 'ts',
        resolveDir: here,
      };
    });
    b.onResolve({ filter: /^@remotion\// }, (a) => ({ errors: [{ text: `unexpected Remotion import ${a.path} (from ${a.importer})` }] }));
  },
};

const result = await esbuild.build({
  entryPoints: [path.join(here, 'src/main.tsx')],
  bundle: true,
  minify: true,
  format: 'iife',
  target: ['es2020'],
  jsx: 'automatic',
  write: false,
  metafile: true,
  legalComments: 'none',
  nodePaths: [path.join(promo, 'node_modules')],
  define: { 'process.env.NODE_ENV': '"production"' },
  plugins: [shims],
  logLevel: 'warning',
});

let js = result.outputFiles[0].text;
// never let the bundle close the inline <script> early
js = js.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');

const kb = (n) => (n / 1024).toFixed(0) + ' KB';
const byPkg = {};
for (const [file, info] of Object.entries(result.metafile.outputs[Object.keys(result.metafile.outputs)[0]].inputs)) {
  const m = file.match(/node_modules[\\/](@[^\\/]+[\\/][^\\/]+|[^\\/]+)/);
  const key = m ? m[1].replace(/\\/g, '/') : file.includes('sahur-promo') ? 'promo models (marketing/video/sahur-promo/src)' : 'game3d/src';
  byPkg[key] = (byPkg[key] || 0) + info.bytesInOutput;
}
console.log('bundle', kb(js.length));
for (const [k, v] of Object.entries(byPkg).sort((a, b) => b[1] - a[1]).slice(0, 12)) console.log('  ', k.padEnd(52), kb(v));

fs.mkdirSync(path.join(here, 'dist'), { recursive: true });
fs.writeFileSync(path.join(here, 'dist/r3d.js'), js);
if (check) process.exit(0);

let html = fs.readFileSync(HTML, 'utf8');
const block = `${BEGIN}\n<script id="r3dBundle">${js}</script>\n${END}`;
const a = html.indexOf(BEGIN.slice(0, 16)), b = html.indexOf(END);
if (a >= 0 && b > a) html = html.slice(0, a) + block + html.slice(b + END.length);
else {
  const i = html.lastIndexOf('</body>');
  if (i < 0) throw new Error('no </body> in Sahur_Protocol.html');
  html = html.slice(0, i) + block + '\n' + html.slice(i);
}
fs.writeFileSync(HTML, html);
console.log('Sahur_Protocol.html', kb(Buffer.byteLength(html)), '(' + (Buffer.byteLength(html) / 1048576).toFixed(2) + ' MB)');
